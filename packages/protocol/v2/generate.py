#!/usr/bin/env python3
"""Generate the shared v2 quote layout from the canonical schema."""
import argparse
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
schema = json.loads((HERE / "schema.json").read_text())
domain, quote = schema["domain"], schema["quote"]
fields = [*domain["fields"], *quote["fields"]]
widths = {"uint256": 32, "bytes32": 32, "address": 20, "uint64": 8, "uint8": 1}
type_string = quote["type"] + "(" + ",".join(f"{kind} {name}" for name, kind in quote["fields"]) + ")"
positions = {name: index * 32 for index, (name, _) in enumerate(fields)}
constants = {
    "domainName": domain["name"], "domainVersion": domain["version"], "domainType": domain["type"],
    "quoteType": type_string,
    "fieldCount": len(fields), "unsignedSize": len(fields) * 32, "signatureSize": quote["signature"]["size"],
    "escrowMode": quote["mode"]["escrow"], "directMode": quote["mode"]["direct"],
    "ownerRole": quote["payerRole"]["owner"], "renterRole": quote["payerRole"]["renter"],
    "pilotChain": int(schema["pilot"]["chainId"]),
    **{f"{name}Offset": index for name, index in positions.items()},
    **{f"status{name[0].upper()}{name[1:]}": value for name, value in schema["errors"].items()},
}
width_text = ", ".join(str(widths[kind]) for _, kind in fields)


def snake(name):
    return re.sub("([a-z])([A-Z])", r"\1_\2", name).upper()


def generate():
    root = HERE.parent
    comment = "Generated by v2/generate.py from v2/schema.json."
    return {
        root / "c/include/nu54_quote_v2_generated.h":
            f"/* {comment} */\n#ifndef NU54_QUOTE_V2_GENERATED_H\n#define NU54_QUOTE_V2_GENERATED_H\n"
            + "".join(f"#define NU54_V2_{snake(k)} {json.dumps(v)}\n" for k, v in constants.items())
            + f"#define NU54_V2_WIDTHS {{ {width_text} }}\n#endif\n",
        root / "ts/src/quote-v2-layout.ts":
            f"// {comment}\n"
            + "".join(f"export const {k} = {json.dumps(v)};\n" for k, v in constants.items())
            + f"export const widths = [{width_text}] as const;\n",
        root / "go/quotev2/layout.go":
            f"// {comment}\npackage quotev2\n\n"
            + "".join(f"const {k} = {json.dumps(v)}\n" for k, v in constants.items())
            + f"\nvar widths = [...]int{{{width_text}}}\n",
        root / "python/nu54_protocol/_quote_v2_layout.py":
            f"# {comment}\n"
            + "".join(f"{snake(k)} = {json.dumps(v)}\n" for k, v in constants.items())
            + f"WIDTHS = ({width_text})\n",
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for filename, generated in generate().items():
        if args.check:
            if filename.read_text() != generated:
                raise SystemExit(f"Quote layout differs from schema: {filename}")
        else:
            filename.write_text(generated)
