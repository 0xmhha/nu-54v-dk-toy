#!/usr/bin/env python3
"""Generate Go and TypeScript service rules from the shared v2 service contract."""

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
PROTOCOL = HERE.parent
CHOICES = {
    PROTOCOL / "go/service/registry_gen.go": lambda body: "// Code generated by generate_services.py; DO NOT EDIT.\n\npackage service\n\nconst registryJSON = `" + body + "`\n",
    PROTOCOL / "ts/src/service-rules-v2.ts": lambda body: "// Generated by generate_services.py.\nexport const SERVICE_V2_RULES = " + body.rstrip() + " as const;\n",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    body = json.dumps(json.loads((HERE / "service-contracts.json").read_bytes()), indent=2, sort_keys=True) + "\n"
    for output, render in CHOICES.items():
        expected = render(body)
        if args.check:
            if not output.is_file() or output.read_text() != expected:
                parser.exit(1, f"stale: {output}\n")
        else:
            output.write_text(expected)


if __name__ == "__main__":
    main()
